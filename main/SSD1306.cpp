void SSD1306::sendCommand(uint8_t cmd) {
    bus_.writeReg(addr_, 0x00, cmd);
}

bool SSD1306::init() {
    sendCommand(0xAE);
    sendCommand(0xD5); sendCommand(0x80);
    sendCommand(0xA8); sendCommand(0x3F);
    sendCommand(0xD3); sendCommand(0x00);
    sendCommand(0x40);
    sendCommand(0x8D); sendCommand(0x14);
    sendCommand(0x20); sendCommand(0x00);
    sendCommand(0xA1);
    sendCommand(0xC8);
    sendCommand(0xDA); sendCommand(0x12);
    sendCommand(0x81); sendCommand(0xCF);
    sendCommand(0xD9); sendCommand(0xF1);
    sendCommand(0xDB); sendCommand(0x40);
    sendCommand(0xA4);
    sendCommand(0xA6);
    sendCommand(0xAF);

    clear();
    flush();
    return true;
}

void SSD1306::clear() {
    std::memset(buffer_, 0, sizeof(buffer_));
}

void SSD1306::setPixel(int x, int y, bool color) {
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (color) {
        buffer_[x + (y / 8) * 128] |= (1 << (y % 8));
    } else {
        buffer_[x + (y / 8) * 128] &= ~(1 << (y % 8));
    }
}

void SSD1306::drawChar(int x, int y, char c) {
    if (c >= 'a' && c <= 'z') {
        c = c - 'a' + 'A';
    }

    if (c < 32 || c > 90) return;
    int idx = c - 32;

    for (int col = 0; col < 5; col++) {
        uint8_t line = font_ascii[idx][col];
        for (int row = 0; row < 7; row++) {
            setPixel(x + col, y + row, (line >> row) & 0x01);
        }
    }
}

void SSD1306::drawString(int x, int y, const char* str) {
    while (*str) {
        drawChar(x, y, *str++);
        x += 6;
    }
}

void SSD1306::flush() {
    sendCommand(0x21); sendCommand(0); sendCommand(127);
    sendCommand(0x22); sendCommand(0); sendCommand(7);
    
    for (size_t i = 0; i < 1024; i += 64) {
        bus_.writeBytes(addr_, 0x40, buffer_ + i, 64);
    }
}

